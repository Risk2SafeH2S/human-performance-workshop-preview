#!/usr/bin/env node
/* Builds the marketing preview edition into ../pathway-preview/.
   Run: node pathway/build-preview.js
   The preview ships only the content it shows: one open module per level. Locked modules keep
   their title, objective and tools; facilitator notes, model answers, practical briefs, capstone
   briefs and the programme toolkit are left out of the output files altogether. */
const fs = require("fs"), path = require("path");
const SRC = __dirname, OUT = path.join(SRC, "..", "pathway-preview");

/* ---- what the preview opens: one module per level ---- */
const OPEN = { L1: "L1M1", L2: "L2M2", L3: "L3M4", L4: "L4M2", L5: "L5M1" };
const GLOSSARY_TERMS = 18;
const CONTACT = {
  org: "H²S Consultants · Risk2Safe",
  pitch: "Human factors, process safety and HSE consulting for oil and gas, grounded in Energy Institute, IOGP and HSE guidance and 30 years of operator-side experience in the Gulf.",
  email: "info@risk2safe.com",
  phone: "+91 90031 46969",
  links: [["risk2safe.com", "https://risk2safe.com"], ["app.risk2safe.com", "https://app.risk2safe.com"]]
};

/* ---- load the full content ---- */
const levels = []; let prog = null;
global.HP = { level: o => levels.push(o), programme: o => { prog = o; } };
require(path.join(SRC, "content", "programme.js"));
for (const n of [1, 2, 3, 4, 5]) require(path.join(SRC, "content", `L${n}.js`));
const words = h => h.replace(/<[^>]+>/g, " ").split(/\s+/).filter(Boolean).length;

/* ---- trim ---- */
const pvLevels = levels.map(L => {
  if (!L.modules.some(m => m.id === OPEN[L.id])) throw new Error("No open module for " + L.id);
  return {
    id: L.id, n: L.n, name: L.name, title: L.title, badge: L.badge, tagline: L.tagline, audience: L.audience,
    prereq: L.prereq, duration: L.duration, format: L.format, outcomes: L.outcomes, competencies: L.competencies,
    schedule: L.schedule,
    modules: L.modules.map(m => m.id === OPEN[L.id]
      ? { id: m.id, n: m.n, t: m.t, mins: m.mins, obj: m.obj, tools: m.tools, learn: m.learn,
          activity: { title: m.activity.title, time: m.activity.time, scn: m.activity.scn, qs: m.activity.qs },
          quiz: m.quiz, nfac: m.activity.fac.length }
      : { id: m.id, n: m.n, t: m.t, mins: m.mins, obj: m.obj, tools: m.tools, locked: true, quiz: [],
          nq: m.quiz.length, words: Math.round(words(m.learn) / 100) * 100, exTitle: m.activity.title, exTime: m.activity.time }),
    assessment: { summary: L.assessment.summary, pass: L.assessment.pass, practical: null },
    capstone: L.capstone ? { title: L.capstone.title, deliverables: L.capstone.deliverables, brief: null } : null
  };
});
const step = Math.floor(prog.glossary.length / GLOSSARY_TERMS);
const pvProg = {
  frameworkIntro: prog.frameworkIntro, routes: prog.routes, proficiency: prog.proficiency, references: prog.references,
  glossary: prog.glossary.filter((_, i) => i % step === 0).slice(0, GLOSSARY_TERMS), glossaryTotal: prog.glossary.length,
  toolkit: null,
  toolkitTeaser: [...prog.toolkit.matchAll(/<h2>(.*?)<\/h2>/g)].map(x => x[1])
};

/* ---- write ---- */
fs.mkdirSync(path.join(OUT, "content"), { recursive: true });
const js = "/* Generated by pathway/build-preview.js. Do not edit: change the full content and rebuild. */\n" +
  `HP.preview=${JSON.stringify(CONTACT)};\nHP.programme(${JSON.stringify(pvProg)});\n` +
  pvLevels.map(L => `HP.level(${JSON.stringify(L)});`).join("\n") + "\n";
fs.writeFileSync(path.join(OUT, "content", "preview.js"), js);

let html = fs.readFileSync(path.join(SRC, "index.html"), "utf8");
const tags = /<script src="content\/programme\.js"><\/script>[\s\S]*?<script src="content\/L5\.js"><\/script>/;
if (!tags.test(html)) throw new Error("content script tags not found in index.html");
html = html.replace(tags, '<script src="content/preview.js"></script>')
  .replace("<title>Human Performance Pathway</title>", "<title>Human Performance Pathway Preview</title>")
  .replace(/<meta name="description" content="[^"]*">/, '<meta name="description" content="Preview of the five-level Human Performance Pathway training pack for oil and gas teams by H²S Consultants. One sample module is open at each level.">\n<meta property="og:title" content="Human Performance Pathway – Preview">\n<meta property="og:description" content="Five levels from workforce awareness to master practitioner. Try one complete module at each level.">\n<meta property="og:type" content="website">')
  .replace("<small>Training pack · H²S Consultants</small></div><span class=\"chip or\">HP-1 to HP-5</span>", "<small>Course preview · H²S Consultants</small></div><span class=\"chip or\">PREVIEW</span>");
if (!html.includes("PREVIEW</span>")) throw new Error("top bar not rewritten");
fs.writeFileSync(path.join(OUT, "index.html"), html);

const total = levels.reduce((a, L) => a + L.modules.length, 0);
console.log(`Preview built: ${Object.keys(OPEN).length} of ${total} modules open, preview.js ${(js.length / 1024).toFixed(0)} KB`);
